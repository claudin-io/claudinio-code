        assert!(is_current_install(&format!("mlx-{MLX_VERSION}")));
        assert!(is_current_install(&format!("mtplx-{MTPLX_VERSION}")));
        assert!(is_current_install(&format!("{LLAMA_BUILD}-macos-arm64")));
