    #[test]
    fn extract_tar_gz_rejects_a_traversing_entry() {
        use std::io::Write;
        let tmp = tempfile::tempdir().unwrap();
        let archive = tmp.path().join("evil.tar.gz");
        {
            let file = std::fs::File::create(&archive).unwrap();
            let enc = flate2::write::GzEncoder::new(file, flate2::Compression::fast());
            let mut builder = tar::Builder::new(enc);
            let payload = b"pwned";
            let mut header = tar::Header::new_gnu();
            header.set_size(payload.len() as u64);
            header.set_mode(0o644);
            // `set_path`/`append_data` refuse to write a `..` component, so
            // the name is planted straight into the header bytes — which is
            // exactly what a hostile archive off the network would contain.
            let name = b"../evil";
            header.as_old_mut().name[..name.len()].copy_from_slice(name);
            header.set_cksum();
            builder.append(&header, &payload[..]).unwrap();
            let mut enc = builder.into_inner().unwrap();
            enc.flush().unwrap();
            enc.finish().unwrap();
        }
        let dest = tmp.path().join("out");
        std::fs::create_dir_all(&dest).unwrap();
        assert!(extract_tar_gz(&archive, &dest).is_err());
        assert!(!tmp.path().join("evil").exists());
    }

    #[test]
    fn extract_tar_gz_flattens_the_tag_directory() {
        use std::io::Write;
        let tmp = tempfile::tempdir().unwrap();
        let archive = tmp.path().join("llama.tar.gz");
        {
            let file = std::fs::File::create(&archive).unwrap();
            let enc = flate2::write::GzEncoder::new(file, flate2::Compression::fast());
            let mut builder = tar::Builder::new(enc);
            for name in ["llama-b1/llama-server", "llama-b1/libllama.dylib"] {
                let payload = b"binary";
                let mut header = tar::Header::new_gnu();
                header.set_size(payload.len() as u64);
                header.set_mode(0o755);
                header.set_cksum();
                builder
                    .append_data(&mut header, name, &payload[..])
                    .unwrap();
            }
            let mut enc = builder.into_inner().unwrap();
            enc.flush().unwrap();
            enc.finish().unwrap();
        }
        let dest = tmp.path().join("out");
        extract_tar_gz(&archive, &dest).unwrap();
        assert!(dest.join("llama-server").is_file());
        assert!(dest.join("libllama.dylib").is_file());
        assert!(!dest.join("llama-b1").exists());
    }

