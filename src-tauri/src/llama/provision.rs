//! Getting a `llama-server` onto disk.
//!
//! Local inference runs as a **sidecar process**, not as in-process bindings.
//! Compiling llama.cpp ourselves would put a C++/CMake toolchain on all six
//! release targets, break the windows-arm64 cross build, and turn the GPU
//! backend into a build-time decision — one bundle per accelerator. Fetching
//! the upstream `llama-server` keeps the backend a runtime choice and keeps our
//! build matrix exactly as it is.
//!
//! GitHub's release API publishes immutable per-tag asset URLs and a size, but
//! no checksum, so the hashes below are computed by `scripts/pin_llama.py` and
//! committed — same arrangement as the Chromium build in `browser::provision`
//! and the embedding model in `code_intel::embeddings`.

use crate::download::{DEFAULT_RETRIES, ProgressFn, download_verified_with_retries};
use crate::net_activity::NetSource;
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

pub struct LlamaAsset {
    /// The substring between "bin-" and the extension in the asset name, e.g.
    /// "macos-arm64". Also the leaf of the install directory.
    pub target: &'static str,
    pub archive: Archive,
    pub sha256: &'static str,
    pub size: u64,
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Archive {
    TarGz,
    Zip,
}

/// Which upstream build to fetch. Persisted in `LocalPrefs`, so a user whose
/// Vulkan driver breaks can drop to CPU without re-downloading their models.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Backend {
    #[default]
    Auto,
    Cpu,
    Vulkan,
}

// GENERATED by scripts/pin_llama.py — do not hand-edit.
include!("llama_pins.rs");

const BASE_URL: &str = "https://github.com/ggml-org/llama.cpp/releases/download";

/// Written only after a complete extraction, so a crash mid-unpack can never
/// leave a half-populated directory that looks installed. Contains the build
/// tag, which is what `gc_stale_installs` compares against.
const READY_MARKER: &str = ".ready";

/// Preferred → fallback asset targets for this host, most capable first.
/// Empty on a target upstream does not publish (32-bit, BSD, macOS on nothing).
pub fn host_targets(backend: Backend) -> &'static [&'static str] {
    match (std::env::consts::OS, std::env::consts::ARCH, backend) {
        // Metal is compiled into the macOS builds; there is no separate asset.
        ("macos", "aarch64", _) => &["macos-arm64"],
        ("macos", "x86_64", _) => &["macos-x64"],
        ("linux", "x86_64", Backend::Cpu) => &["ubuntu-x64"],
        ("linux", "x86_64", _) => &["ubuntu-vulkan-x64", "ubuntu-x64"],
        ("linux", "aarch64", Backend::Cpu) => &["ubuntu-arm64"],
        ("linux", "aarch64", _) => &["ubuntu-vulkan-arm64", "ubuntu-arm64"],
        ("windows", "x86_64", Backend::Cpu) => &["win-cpu-x64"],
        ("windows", "x86_64", _) => &["win-vulkan-x64", "win-cpu-x64"],
        ("windows", "aarch64", _) => &["win-cpu-arm64"],
        _ => &[],
    }
}

/// The target actually used for this host: the first pinned candidate, except
/// that `Auto` only takes a Vulkan build when a loader is present. A Vulkan
/// binary without `vulkan-1.dll`/`libvulkan.so.1` exits at startup, and a
/// download that can never run is worse than a slower CPU build.
pub fn resolved_target(backend: Backend) -> Option<&'static str> {
    let candidates = host_targets(backend);
    let skip_vulkan = backend == Backend::Auto && !has_vulkan_loader();
    candidates
        .iter()
        .find(|t| !(skip_vulkan && t.contains("vulkan")))
        .or_else(|| candidates.first())
        .copied()
        .filter(|t| asset_for(t).is_some())
}

pub fn asset_for(target: &str) -> Option<&'static LlamaAsset> {
    LLAMA_ASSETS.iter().find(|a| a.target == target)
}

pub fn artifact_url(build: &str, target: &str) -> Option<String> {
    let asset = asset_for(target)?;
    let ext = match asset.archive {
        Archive::TarGz => "tar.gz",
        Archive::Zip => "zip",
    };
    Some(format!(
        "{BASE_URL}/{build}/llama-{build}-bin-{target}.{ext}"
    ))
}

/// Root for everything this module owns, under the machine-local app data dir.
/// Never inside the workspace: the weights are mmapped, and an mmap over SMB
/// hangs or corrupts — the lesson already recorded for the index database.
pub fn llama_dir() -> Result<PathBuf, String> {
    let base = dirs::data_dir().ok_or_else(|| "no data directory on this platform".to_string())?;
    Ok(base.join("claudinio-code").join("llama"))
}

/// Install directory for one (build, target) pair, e.g. `b10502-macos-arm64`.
///
/// Keyed by both so a pin bump or a backend switch lands in a fresh directory
/// instead of half-overwriting a live one. Deliberately short for the same
/// Windows MAX_PATH reason as `browser::provision::install_dir`.
pub fn install_dir(target: &str) -> Result<PathBuf, String> {
    Ok(llama_dir()?.join(format!("{LLAMA_BUILD}-{target}")))
}

pub fn exe_name() -> &'static str {
    if cfg!(windows) {
        "llama-server.exe"
    } else {
        "llama-server"
    }
}

/// Absolute path of the managed executable, whether or not it exists yet.
pub fn managed_exe(target: &str) -> Result<PathBuf, String> {
    Ok(install_dir(target)?.join(exe_name()))
}

pub fn is_installed(target: &str) -> bool {
    match (install_dir(target), managed_exe(target)) {
        (Ok(dir), Ok(exe)) => dir.join(READY_MARKER).exists() && exe.exists(),
        _ => false,
    }
}

/// Download and unpack the pinned build if it is not already installed.
///
/// Callers must have user consent before reaching here: this spends 11-35 MB of
/// someone's bandwidth, which is not something a tool call may do on its own.
pub async fn ensure_installed(
    backend: Backend,
    on_progress: Option<&ProgressFn>,
) -> Result<PathBuf, String> {
    let target = resolved_target(backend).ok_or_else(|| {
        format!(
            "no llama.cpp build published for {}-{}",
            std::env::consts::OS,
            std::env::consts::ARCH
        )
    })?;
    let exe = managed_exe(target)?;
    if is_installed(target) {
        return Ok(exe);
    }
    let asset = asset_for(target).expect("resolved_target only returns pinned targets");
    let url = artifact_url(LLAMA_BUILD, target).expect("pinned target has a URL");

    let dir = install_dir(target)?;
    // A previous attempt may have died mid-unpack; start clean rather than
    // extracting over the wreckage.
    if dir.exists() {
        std::fs::remove_dir_all(&dir).map_err(|e| format!("clear {}: {e}", dir.display()))?;
    }
    std::fs::create_dir_all(&dir).map_err(|e| format!("create {}: {e}", dir.display()))?;

    let ext = match asset.archive {
        Archive::TarGz => "tar.gz",
        Archive::Zip => "zip",
    };
    let archive_path = llama_dir()?.join(format!("llama-{LLAMA_BUILD}-{target}.{ext}"));
    let label = format!("llama.cpp {LLAMA_BUILD} ({target})");
    download_verified_with_retries(
        &url,
        &archive_path,
        &label,
        asset.sha256,
        asset.size,
        NetSource::LlamaServerDownload,
        on_progress,
        DEFAULT_RETRIES,
    )
    .await?;

    let kind = asset.archive;
    let archive_for_task = archive_path.clone();
    let dir_for_task = dir.clone();
    // Decompressing tens of MB is blocking CPU and file I/O; leaving it on an
    // async worker would stall every other task on the runtime.
    tokio::task::spawn_blocking(move || match kind {
        Archive::TarGz => extract_tar_gz(&archive_for_task, &dir_for_task),
        Archive::Zip => extract_zip(&archive_for_task, &dir_for_task),
    })
    .await
    .map_err(|e| format!("extract task failed: {e}"))??;

    let _ = std::fs::remove_file(&archive_path);

    if !exe.exists() {
        return Err(format!(
            "extracted archive is missing {} at {}",
            exe_name(),
            dir.display()
        ));
    }
    std::fs::write(dir.join(READY_MARKER), LLAMA_BUILD)
        .map_err(|e| format!("write ready marker: {e}"))?;
    Ok(exe)
}

/// Remove every managed install, leaving downloaded models alone.
pub fn uninstall() -> Result<(), String> {
    let dir = llama_dir()?;
    if dir.exists() {
        std::fs::remove_dir_all(&dir).map_err(|e| format!("remove {}: {e}", dir.display()))?;
    }
    Ok(())
}

/// Delete installs from an older pin. Without this every bump leaks a full
/// copy of the runtime, and the user has no way to see it.
/// Whether a directory under `llama_dir()` belongs to a runtime this build
/// still uses.
///
/// Every runtime installed here must be listed. The sweep deletes whatever is
/// not, so an omission is not a leak — it is the app erasing a working install
/// on the next launch, then reporting the runtime as missing. That is exactly
/// what happened to MTPLX: 588 MB removed at startup, and a "not installed"
/// error pointing at a Settings button the user had already pressed.
fn is_current_install(name: &str) -> bool {
    name.starts_with(&format!("{LLAMA_BUILD}-"))
        || name == format!("mlx-{MLX_VERSION}")
        || name == format!("mtplx-{MTPLX_VERSION}")
}

pub fn gc_stale_installs() {
    let Ok(dir) = llama_dir() else { return };
    let Ok(entries) = std::fs::read_dir(&dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if !path.is_dir() {
            continue;
        }
        let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
        if !is_current_install(name) {
            let _ = std::fs::remove_dir_all(&path);
        }
    }
}

