/// Download and unpack the pinned MLX sidecar.
///
/// Ours rather than upstream's, but pinned by sha256 all the same: being our
/// own artifact says nothing about the network it arrives over.
pub async fn ensure_mlx_installed(on_progress: Option<&ProgressFn>) -> Result<PathBuf, String> {
    if !cfg!(all(target_os = "macos", target_arch = "aarch64")) {
        return Err("the MLX engine is Apple Silicon only".into());
    }
    let exe = mlx_exe()?;
    if mlx_installed() {
        return Ok(exe);
    }

    let dir = mlx_install_dir()?;
    if dir.exists() {
        std::fs::remove_dir_all(&dir).map_err(|e| format!("clear {}: {e}", dir.display()))?;
    }
    std::fs::create_dir_all(&dir).map_err(|e| format!("create {}: {e}", dir.display()))?;

    let archive_path = llama_dir()?.join(format!("claudinio-mlx-{MLX_VERSION}.tar.gz"));
    download_verified_with_retries(
        &mlx_artifact_url(),
        &archive_path,
        &format!("claudinio-mlx {MLX_VERSION}"),
        MLX_SHA256,
        MLX_SIZE,
        NetSource::LlamaServerDownload,
        on_progress,
        DEFAULT_RETRIES,
    )
    .await?;

    let archive_for_task = archive_path.clone();
    let dir_for_task = dir.clone();
    tokio::task::spawn_blocking(move || extract_tar_gz(&archive_for_task, &dir_for_task))
        .await
        .map_err(|e| format!("extract task failed: {e}"))??;
    let _ = std::fs::remove_file(&archive_path);

    if !exe.is_file() {
        return Err(format!(
            "extracted archive is missing claudinio-mlx at {}",
            dir.display()
        ));
    }
    // Without the shader bundle the binary starts and dies on first use, which
    // presents as a mystery timeout rather than a missing file.
    if !dir.join("mlx-swift_Cmlx.bundle").exists() {
        return Err("extracted archive is missing the Metal shader bundle".into());
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(&exe, std::fs::Permissions::from_mode(0o755));
    }
    std::fs::write(dir.join(READY_MARKER), MLX_VERSION)
        .map_err(|e| format!("write ready marker: {e}"))?;
    Ok(exe)
}

